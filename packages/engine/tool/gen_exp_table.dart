// Generates lib/src/core/exp_table.g.dart: exp(-x) as Fx raw values.
//
// This runs once on the developer's machine. The engine only ever reads the
// committed integer table, so platform differences in dart:math never reach
// the simulation. Run from packages/engine:
//
//   dart run tool/gen_exp_table.dart

import 'dart:io';
import 'dart:math' as math;

import 'package:engine/src/core/fx.dart';

const stepsPerUnit = 64;
const maxX = 10;

void main() {
  final values = [
    for (var i = 0; i <= stepsPerUnit * maxX; i++)
      (math.exp(-i / stepsPerUnit) * Fx.scale).round(),
  ];
  final rows = [
    for (var i = 0; i < values.length; i += 12)
      '  ${values.skip(i).take(12).join(', ')},',
  ];
  File('lib/src/core/exp_table.g.dart').writeAsStringSync('''
// GENERATED by tool/gen_exp_table.dart. Do not edit.

/// Table entries per unit of x.
const int expTableStepsPerUnit = $stepsPerUnit;

/// `exp(-i / expTableStepsPerUnit)` as Fx raw values, for x from 0 to $maxX.
// dart format off
const List<int> expTable = [
${rows.join('\n')}
];
// dart format on
''');
  stdout.writeln('Wrote ${values.length} entries.');
}
